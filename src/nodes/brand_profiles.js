// --- ქვემოთ შეცვლა არ არის საჭირო ---
const msg = $('Telegram Trigger').first().json.message || {};
const raw = String(msg.text ?? msg.caption ?? '').trim();
const m = raw.match(/^#([a-z0-9_]+)/i);
const requested = m ? m[1].toLowerCase() : null;
const found = Boolean(requested && BRANDS[requested]);
const key = found ? requested : DEFAULT_BRAND;

return [{
  json: {
    brand_key: key,
    brand_tag: found ? m[0] : '',
    available_brands: Object.keys(BRANDS).map(k => '#' + k).join(', '),
    ...BRANDS[key],
  },
}];
